export function getOfficialCatalogueProducts(): Product[] {
  return CATALOGUE_ITEMS.map((item, index) => {
    const mainImg = generateProductSvg(item.code, item.subcategory, item.brand, 'main', undefined, item.forzaCode, item.cataloguePage);
    const specImg = generateProductSvg(item.code, item.subcategory, item.brand, 'spec', undefined, item.forzaCode, item.cataloguePage);
    const certImg = generateProductSvg(item.code, item.subcategory, item.brand, 'cert', undefined, item.forzaCode, item.cataloguePage);

    return {
      code: item.code,
      name: item.name,
      nameEn: item.nameEn,
      brand: item.brand,
      categorySlug: item.categorySlug,
      categoryName: item.categoryName,
      subcategory: item.subcategory,
      forzaCode: item.forzaCode,
      cataloguePage: item.cataloguePage,
      stock: item.stock,
      inquiryOnly: item.inquiryOnly,
      unit: item.unit,
      featured: item.featured ?? (index < 12),
      discountPercent: index % 5 === 0 ? 10 : 0,
      minOrderQty: 1,
      tags: item.tags,
      description: item.description,
      technicalSpecs: item.specs,
      prices: {
        base: item.basePrice,
        retail: item.retailPrice,
        wholesale: item.wholesalePrice,
        dealer: item.dealerPrice,
      },
      clubPointsReward: Math.max(20, Math.round(item.retailPrice / 60000)),
      images: [mainImg, specImg, certImg],
    };
  });
}
